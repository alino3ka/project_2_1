@st.cache_data
def load_data():
    """
    Загружает очищенные данные из CSV, используя безопасные пути.
    Преобразует сериализованные списки обратно в Python-списки.

    :return: DataFrame с данными о фильмах
    """
    project_root = Path(__file__).resolve().parents[1]
    csv_path = project_root / "data" / "processed" / "movies_clean.csv"

    df = pd.read_csv(
        csv_path,
        converters={
            "Режиссер": ast.literal_eval,
            "Жанр": ast.literal_eval,
            "Продюсер": ast.literal_eval,
            "Сценарист": ast.literal_eval,
            "Композитор": ast.literal_eval,
            "Монтажер": ast.literal_eval,
            "Оператор": ast.literal_eval,
            "Страна": ast.literal_eval,
            "Формат": ast.literal_eval,
            "title_lemmas": ast.literal_eval
        }
    )
    return df


